if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/* -------------------------------------------------------------------------
 * 1) ปิด XML-RPC
 * ช่องทางที่บอตใช้ยิงเดารหัสผ่านรัว ๆ และใช้ขยายการโจมตี DDoS
 * ถ้าคุณใช้แอป WordPress บนมือถือ หรือใช้ Jetpack ให้ลบบล็อกนี้ออก
 * ---------------------------------------------------------------------- */
add_filter( 'xmlrpc_enabled', '__return_false' );
add_filter( 'xmlrpc_methods', '__return_empty_array' );
add_filter( 'wp_headers', function ( $headers ) {
	unset( $headers['X-Pingback'] );
	return $headers;
} );

/* -------------------------------------------------------------------------
 * 2) ปิดการเปิดเผยรายชื่อผู้ใช้ผ่าน REST API
 * ตอนนี้ /wp-json/wp/v2/users เปิดให้ใครก็ได้ดูว่ามีบัญชีอะไรบ้าง
 * เท่ากับยกชื่อผู้ใช้ให้คนที่จะมาเดารหัสผ่านฟรี ๆ
 * ยกเว้น /users/me ไว้ เพราะระบบภายในและการเชื่อมต่อผ่าน API ต้องใช้
 * ---------------------------------------------------------------------- */
add_filter( 'rest_endpoints', function ( $endpoints ) {
	if ( is_user_logged_in() ) {
		return $endpoints;
	}
	unset( $endpoints['/wp/v2/users'] );
	unset( $endpoints['/wp/v2/users/(?P<id>[\d]+)'] );
	return $endpoints;
} );

/* -------------------------------------------------------------------------
 * 3) ถอดออกแล้ว — เดิมเป็นการบล็อก ?author=1
 *
 * เหตุผลที่ถอด: เว็บนี้มี author archive อยู่ใน sitemap จริง 2 URL
 *   https://wecleanvr.com/author/wecleanadmin/
 *   https://wecleanvr.com/author/wecraftsale/
 * การบล็อกจะทำให้ URL ที่ Google เก็บไว้แล้วพัง โดยที่ไม่ได้ปิดอะไรเลย
 * เพราะชื่อผู้ใช้ถูกเปิดเผยผ่าน author archive อยู่แล้ว
 *
 * แนวป้องกันที่ถูกต้องสำหรับเว็บนี้คือทำให้ "เดารหัสผ่านไม่ได้" แทนการ
 * "ซ่อนชื่อผู้ใช้" ได้แก่ ตั้งรหัสผ่านที่ยาวและไม่ซ้ำ เปิด 2FA และติดตั้ง
 * ปลั๊กอินจำกัดจำนวนครั้งการล็อกอิน (ดู docs/wecleanvr-audit.md)
 * ---------------------------------------------------------------------- */

/* -------------------------------------------------------------------------
 * 4) ปิดการแก้ไฟล์ธีมและปลั๊กอินจากหน้า admin
 * ถ้ามีคนแฮกเข้าหน้า admin ได้ จะได้ฝังโค้ดลงไฟล์เว็บไม่ได้
 * ต้องแก้ไฟล์จริง ๆ ให้ใช้ File Manager ของ Plesk แทน
 * ---------------------------------------------------------------------- */
if ( ! defined( 'DISALLOW_FILE_EDIT' ) ) {
	define( 'DISALLOW_FILE_EDIT', true );
}

/* -------------------------------------------------------------------------
 * 5) ไม่ให้ error ของ PHP แสดงบนหน้าเว็บ
 * ตอนนี้หน้า admin ขึ้นข้อความ deprecated ของ Elementor พร้อม path จริง
 * บนเซิร์ฟเวอร์ ซึ่งไม่ควรให้คนนอกเห็น
 * นี่เป็นแค่ตัวกันไว้ชั้นหนึ่ง ทางแก้จริงคือตั้ง WP_DEBUG เป็น false
 * ใน wp-config.php (ดู docs/wecleanvr-audit.md)
 * ---------------------------------------------------------------------- */
@ini_set( 'display_errors', '0' );

/* -------------------------------------------------------------------------
 * 6) ไม่บอกเลขเวอร์ชัน WordPress ใน source code ของหน้าเว็บ
 * ---------------------------------------------------------------------- */
remove_action( 'wp_head', 'wp_generator' );
add_filter( 'the_generator', '__return_empty_string' );
